const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const Database = require('better-sqlite3');

test('pitch speed persists, exports, and is captured with generated matchups', {timeout:600000}, async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'gf_speed_test_'));
  process.env.DB_PATH = path.join(dir,'test.db');
  process.env.FFMPEG_PATH = require('ffmpeg-static');
  process.env.FFPROBE_PATH = require('ffprobe-static').path;
  const {startServer,closeDatabase} = require('../server');
  const server = startServer(0,'127.0.0.1');
  await new Promise(resolve=>server.listening ? resolve() : server.once('listening',resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  const db = new Database(process.env.DB_PATH);
  try {
    const video = path.join(dir,'source.mp4');
    const encoded = spawnSync(process.env.FFMPEG_PATH,['-y','-f','lavfi','-i','testsrc2=s=240x320:r=60','-t','2','-c:v','libx264','-pix_fmt','yuv420p',video],{windowsHide:true});
    assert.equal(encoded.status,0,encoded.stderr?.toString());
    const blob = fs.readFileSync(video);
    db.prepare("INSERT INTO teams(id,name) VALUES(1,'Test team')").run();
    db.prepare("INSERT INTO pitchers(id,team_id,name) VALUES(1,1,'Test pitcher')").run();
    db.prepare('INSERT INTO pitch_clips(id,description,clip_blob,fps,contact_frame) VALUES(1,?,?,?,?)').run('Speed test',blob,60,119);
    db.prepare('INSERT INTO swing_clips(id,description,clip_blob,fps,frame_count,decision_frame,swing_seconds) VALUES(1,?,?,60,120,100,2)').run('Swing test',blob);
    const post = (route,body)=>fetch(url+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
    const upload = new FormData();
    for (const [key,value] of Object.entries({team_id:'1',pitcher_id:'1',contact_frame:'119',fps:'60'})) upload.append(key,value);
    upload.append('file',new Blob([blob],{type:'video/mp4'}),'pitch.mp4');
    const created = await fetch(url+'/upload/pitch/finalize',{method:'POST',body:upload,redirect:'manual'});
    assert.equal(created.status,303,await created.clone().text());
    assert.match(created.headers.get('location'),/^\/pitch\/speed\?/);
    const payload = {pitch_id:1,release_frame:90.5,extension:6,contact_adjustment:3,mound_distance:60.5,initial_mph:999};
    let response = await post('/api/pitch/speed',payload);
    assert.equal(response.status,200,await response.clone().text());
    const speed = (await response.json()).speed;
    assert.equal(db.prepare('SELECT release_frame FROM pitch_clips WHERE id=1').get().release_frame,90.5);
    assert.equal(db.prepare('SELECT initial_mph FROM pitch_clips WHERE id=1').get().initial_mph,speed.mph);
    assert.equal((await post('/api/pitch/speed',{...payload,release_frame:119})).status,400);
    assert.equal((await post('/api/pitch/speed',{...payload,pitch_id:999})).status,404);
    response = await fetch(url+'/pitch/speed?id=1');
    assert.equal(response.status,200);
    assert.match(await response.text(),/Save Speed to Pitch/);
    response = await fetch(url+'/export/pitch-speed?id=1');
    assert.equal(response.status,200,await response.clone().text().then(t=>t.slice(0,500)));
    const exported = path.join(dir,'export.mp4');
    fs.writeFileSync(exported,Buffer.from(await response.arrayBuffer()));
    const probe = spawnSync(process.env.FFPROBE_PATH,['-v','error','-show_entries','format=duration','-of','json',exported],{encoding:'utf8',windowsHide:true});
    assert.ok(JSON.parse(probe.stdout).format.duration > 16);
    response = await post('/matchup/create',{pitch_id:1,swing_id:1,description:'Speed matchup'});
    assert.equal(response.status,200,await response.clone().text());
    const id = (await response.json()).id;
    const snapshot = JSON.parse(db.prepare('SELECT pitch_speed_json FROM matchups WHERE id=?').get(id).pitch_speed_json);
    assert.equal(snapshot.release,90.5);
    assert.equal(snapshot.mph,speed.mph);
    await post('/api/pitch/speed',{...payload,extension:7});
    assert.equal(JSON.parse(db.prepare('SELECT pitch_speed_json FROM matchups WHERE id=?').get(id).pitch_speed_json).mph,speed.mph);
    response = await fetch(url+'/play/matchup?id='+id);
    assert.ok((await response.text()).includes(`Pitch speed <strong>${speed.mph.toFixed(1)} mph</strong>`));
    await post('/api/pitch/speed',{...payload,pitch_id:2});
    response = await post('/matchup/bulk',{pitch_ids:[2],swing_ids:[1]});
    assert.equal(response.status,404,'Bulk matchup creation was deliberately removed.');
  } finally {
    db.close(); await new Promise(resolve=>server.close(resolve)); closeDatabase();
    fs.rmSync(dir,{recursive:true,force:true});
  }
});
